import { blueOrange, motion, radii, themes, type ColorTokens, type UpDownTokens } from "./tokens";

const HEADER = `/* AUTO-GENERATED by \`pnpm tokens\` from src/ui/tokens/tokens.ts — do not edit. */`;

function block(selector: string, vars: Partial<ColorTokens> | Record<string, string>): string {
  const lines = Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`);
  return `${selector} {\n${lines.join("\n")}\n}`;
}

/**
 * Themes are scoped by `data-theme`, so any subtree can render in the other
 * theme (the /design page shows both side by side). The direction scheme is
 * scoped by `data-updown` on the same or an ancestor element.
 */
export function buildTokensCss(): string {
  const updown = (theme: "dark" | "light", t: UpDownTokens) =>
    block(
      [
        `[data-theme="${theme}"][data-updown="blue-orange"]`,
        `[data-updown="blue-orange"] [data-theme="${theme}"]`,
        `[data-theme="${theme}"] [data-updown="blue-orange"]`,
      ].join(",\n"),
      t,
    );

  return [
    HEADER,
    block(":root", {
      "control-radius": radii.control,
      "popover-radius": radii.popover,
      "dialog-radius": radii.dialog,
      "motion-fast": motion.fast,
      "motion-base": motion.base,
      "motion-slow": motion.slow,
      "motion-flash": motion.flash,
      "motion-ease": motion.ease,
    }),
    block(`:root,\n[data-theme="dark"]`, themes.dark),
    block(`[data-theme="dark"]`, { "color-scheme": "dark" }).replace("--color-scheme", "color-scheme"),
    block(`[data-theme="light"]`, themes.light),
    block(`[data-theme="light"]`, { "color-scheme": "light" }).replace("--color-scheme", "color-scheme"),
    updown("dark", blueOrange.dark),
    updown("light", blueOrange.light),
    "",
  ].join("\n\n");
}
